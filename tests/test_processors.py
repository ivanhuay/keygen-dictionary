# ── _process_numbers ──────────────────────────────────────────────────────────

class TestProcessNumbers:
    def test_single_number_yields_prefixes_and_suffixes(self, maker):
        result = maker._process_numbers("1990")
        assert "1" in result
        assert "19" in result
        assert "199" in result
        assert "1990" in result
        assert "990" in result
        assert "90" in result

    def test_no_numbers_returns_empty(self, maker):
        assert maker._process_numbers("Main Street") == []

    def test_multiple_numbers_in_string(self, maker):
        result = maker._process_numbers("123 456")
        assert "12" in result
        assert "45" in result

    def test_single_digit_yields_only_itself(self, maker):
        result = maker._process_numbers("5")
        assert result == ["5"]

    def test_no_noise_repetitions(self, maker):
        result = maker._process_numbers("111")
        # should not contain repeated digit combos like "111" generated by product
        assert all(len(set(r)) > 0 for r in result)


