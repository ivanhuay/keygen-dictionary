# ── _shannon_entropy ──────────────────────────────────────────────────────────

class TestShannonEntropy:
    def test_empty_string_is_zero(self):
        assert DictionaryMaker._shannon_entropy("") == 0.0

    def test_uniform_string_is_zero(self):
        assert DictionaryMaker._shannon_entropy("aaaa") == 0.0

    def test_entropy_increases_with_variety(self):
        low  = DictionaryMaker._shannon_entropy("aaaa")
        mid  = DictionaryMaker._shannon_entropy("aabb")
        high = DictionaryMaker._shannon_entropy("abcd")
        assert low < mid < high

    def test_predictable_less_than_random(self):
        # "password" has repeated chars → lower entropy than all-unique
        assert DictionaryMaker._shannon_entropy("password") < \
               DictionaryMaker._shannon_entropy("xK9@mN2q")


# ── _passes_length_filter ─────────────────────────────────────────────────────

class TestLengthFilter:
    def test_no_limits_always_passes(self, maker):
        assert maker._passes_length_filter("hi")
        assert maker._passes_length_filter("averylongpassword123")

    def test_min_length_excludes_short(self, maker):
        maker.min_length = 8
        assert not maker._passes_length_filter("short")
        assert maker._passes_length_filter("longenough")

    def test_max_length_excludes_long(self, maker):
        maker.max_length = 8
        assert not maker._passes_length_filter("toolongpassword")
        assert maker._passes_length_filter("short")

    def test_exact_min_passes(self, maker):
        maker.min_length = 5
        assert maker._passes_length_filter("hello")

    def test_exact_max_passes(self, maker):
        maker.max_length = 5
        assert maker._passes_length_filter("hello")

    def test_both_limits(self, maker):
        maker.min_length = 4
        maker.max_length = 8
        assert not maker._passes_length_filter("abc")
        assert maker._passes_length_filter("abcd")
        assert maker._passes_length_filter("abcdefgh")
        assert not maker._passes_length_filter("abcdefghi")


# ── _apply_leet ───────────────────────────────────────────────────────────────

class TestApplyLeet:
    def test_admin_gets_leet_variant(self, maker):
        maker.tokens = ["admin"]
        maker._apply_leet()
        assert "4dm1n" in maker.tokens

    def test_no_duplicates_added(self, maker):
        maker.tokens = ["admin"]
        maker._apply_leet()
        assert maker.tokens.count("4dm1n") == 1

    def test_no_leet_when_no_substitutable_chars(self, maker):
        before = set(maker.tokens)
        maker.tokens = ["xyz"]
        maker._apply_leet()
        # "xyz" has no a/e/i/o/s — no variant should be added
        added = set(maker.tokens) - {"xyz"}
        assert "xyz" not in added

    def test_all_substitutions(self, maker):
        maker.tokens = ["aeiOS"]
        maker._apply_leet()
        assert "43105" in maker.tokens
